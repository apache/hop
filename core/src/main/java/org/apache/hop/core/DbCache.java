package org.apache.hop.core;

import java.util.Enumeration;
import java.util.Hashtable;
import java.util.concurrent.atomic.AtomicInteger;
import lombok.Getter;
import lombok.Setter;
import org.apache.hop.core.row.IRowMeta;

/**
 * This class caches database queries so that the same query doesn't get called twice. Queries are
 * often launched to the databases to get information on tables etc.
 */
public class DbCache {
  private static final DbCache dbCache = new DbCache();

  private volatile Hashtable<DbCacheEntry, IRowMeta> cache;

  /**
   * Bumped every time entries are removed from this cache. Anything which derives row metadata from
   * this cache and keeps the result around can compare the generation it last saw with {@link
   * #getGeneration()} to find out whether its own copy went stale.
   */
  private final AtomicInteger generation = new AtomicInteger();

  /** Held for a clear and for a put that has to agree with that clear. */
  private final Object lock = new Object();

  @Getter @Setter private boolean active;

  public void put(DbCacheEntry entry, IRowMeta fields) {
    if (!active || entry == null || fields == null) {
      return;
    }

    synchronized (lock) {
      cache.put(entry, fields.clone());
    }
  }

  /**
   * Store a row that was just read from the database, unless the cache was cleared after that read
   * started.
   *
   * <p>A check remembers {@link #getGeneration()} before it queries. Clearing the cache while the
   * query is in flight bumps the generation, and the row from that query is the layout from before
   * the clear. Storing it would put the old columns straight back.
   *
   * @param entry the query that produced the row
   * @param fields the row read from the database
   * @param generationAtQuery the generation observed before the query
   * @return true when the row was stored
   */
  public boolean putIfCurrent(DbCacheEntry entry, IRowMeta fields, int generationAtQuery) {
    if (!active || entry == null || fields == null) {
      return false;
    }

    synchronized (lock) {
      if (generation.get() != generationAtQuery) {
        return false;
      }
      cache.put(entry, fields.clone());
      return true;
    }
  }

  /**
   * Get the fields as a row generated by a database cache entry
   *
   * @param entry the entry to look for
   * @return the fields as a row generated by a database cache entry
   */
  public IRowMeta get(DbCacheEntry entry) {
    if (!active) {
      return null;
    }

    IRowMeta fields = cache.get(entry);
    if (fields != null) {
      fields = fields.clone(); // Copy it again!
    }

    return fields;
  }

  public int size() {
    return cache.size();
  }

  /**
   * Clear out all entries of database with a certain name
   *
   * @param dbname The name of the database for which we want to clear the cache or null if we want
   *     to clear it all.
   */
  public void clear(String dbname) {
    synchronized (lock) {
      if (dbname == null) {
        cache = new Hashtable<>();
      } else {
        Enumeration<DbCacheEntry> keys = cache.keys();
        while (keys.hasMoreElements()) {
          DbCacheEntry entry = keys.nextElement();
          if (entry.sameDB(dbname)) {
            // Same name: remove it!
            cache.remove(entry);
          }
        }
      }
      // Only bump the generation once the entries are gone. A reader which sees the new generation
      // and re-derives its row metadata must not be able to pick up the entries we are removing.
      // putIfCurrent holds the same lock, so a query that started before this clear cannot store
      // its row after the generation moves.
      generation.incrementAndGet();
    }
  }

  /**
   * The number of times this cache was cleared. Callers which cache anything derived from the
   * database cache can store this value alongside their own copy and drop that copy as soon as the
   * generation changes.
   *
   * @return the current generation of this cache
   */
  public int getGeneration() {
    return generation.get();
  }

  private DbCache() {
    cache = new Hashtable<>();
    active = true;
  }

  /**
   * @return the database cache instance.
   */
  public static DbCache getInstance() {
    return dbCache;
  }

  /** Clear the whole cache in one go */
  public static void clearAll() {
    getInstance().clear(null);
  }
}
